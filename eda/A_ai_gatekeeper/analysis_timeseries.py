# -*- coding: utf-8 -*-
"""
A. AI 게이트키퍼 EDA — 시계열(2018~2025) 매체별 뉴스 이용률 (지난 1주일, 전체 응답자 기준, 가중치 적용)

지표: 종이신문 열독률, TV 뉴스, 인터넷 포털 뉴스, 온라인 동영상 플랫폼 뉴스, 숏폼 뉴스(2023~), 생성형 AI 뉴스(2025~)

문항 비교 가능성 (각 연도 설문지겸코드북/SAV 라벨 대조):
- 종이신문: 2018~2019는 '종이신문을 통해 신문기사를 본 경험'(있다/없다), 2020~2021은 열독 일수(평일/주말)>0,
  2022~2025는 '지난 일주일 간 종이신문 열독 여부'(읽었다). 공식 보고서가 동일 지표로 시계열 발표 → 비교 가능으로 처리.
- TV 뉴스: 전 연도 'TV 뉴스/시사(보도) 프로그램 시청 여부' 단일 문항 — 비교 가능.
- 포털 뉴스: 2018~2022는 기기별(모바일/PC) 이용 일수 문항(하나라도 1일 이상), 2023~2025는 기기별 이용 여부 문항.
  스킵로직(인터넷/포털 비이용자 미질문)에 의한 NaN은 비이용 처리. 전체 기준 이용률로 비교 가능.
- 온라인 동영상 플랫폼 뉴스: 2018년 첫 조사, 전 연도 이용 여부 단일 문항 — 비교 가능.
- 2022년은 표본(58,936명)·조사설계가 달라 공식 보고서 시계열 그림(그림 1-1)에서도 제외됨 → 별도 표기(점선/각주).
- 2016~2017, 2012~2014는 문항 구조가 달라(신문기사 경로 통합형 등) SAV 재계산 대신 공식 보고서 수치만 참고 표기.
"""
import pyreadstat
import pandas as pd
import numpy as np

from pathlib import Path

_HERE = Path(__file__).resolve().parent
OUT = str(_HERE)
D = str(_HERE.parents[1] / "data")

def load(path, cols):
    df, meta = pyreadstat.read_sav(path, usecols=cols)
    return df

def r(w, mask):
    return round(float(100 * (w * mask.fillna(False)).sum() / w.sum()), 1)

rows = []

# ---- 2018 (n=5,040, 개인가중치 wt2) ----
df = load(f"{D}/2018_언론수용자조사/2018언론수용자의식조사_공개.sav",
          ["Q1_1", "Q58", "Q79", "Q23_1_1", "Q23_1_2", "Q23_2_1", "Q23_2_2", "wt2", "SQ2"])
w = df["wt2"]
portal = (df[["Q23_1_1", "Q23_1_2", "Q23_2_1", "Q23_2_2"]] >= 2).any(axis=1)  # 1=이용안함, 2~6=1~5일
rows.append({"year": 2018, "종이신문": r(w, df["Q1_1"] == 1), "TV 뉴스": r(w, df["Q58"] == 1),
             "포털 뉴스": r(w, portal), "동영상 뉴스": r(w, df["Q79"] == 1),
             "숏폼 뉴스": np.nan, "AI 뉴스": np.nan, "n": len(df)})

# ---- 2019 (n=5,040, 개인가중치 wt1) ----
df = load(f"{D}/2019_언론수용자조사/2019_언론수용자조사.sav",
          ["Q2_1", "Q10", "Q64", "Q39_01_1", "Q39_01_2", "Q39_02_1", "Q39_02_2", "wt1"])
w = df["wt1"]
portal = (df[["Q39_01_1", "Q39_01_2", "Q39_02_1", "Q39_02_2"]] >= 2).any(axis=1)
rows.append({"year": 2019, "종이신문": r(w, df["Q2_1"] == 1), "TV 뉴스": r(w, df["Q10"] == 1),
             "포털 뉴스": r(w, portal), "동영상 뉴스": r(w, df["Q64"] == 1),
             "숏폼 뉴스": np.nan, "AI 뉴스": np.nan, "n": len(df)})

# ---- 2020 / 2021 (n=5,010, WT) ----
for y, p in [(2020, f"{D}/2020_언론수용자조사/2020_언론수용자조사.sav"),
             (2021, f"{D}/2021_언론수용자조사/2021 언론수용자 조사 DATA_통계표_보고서 등/2021 언론수용자 조사 DATA_공개용_최종.sav")]:
    df = load(p, ["Q3x1", "Q3x2", "Q11", "Q66", "Q40x1_1", "Q40x1_2", "Q40x2_1", "Q40x2_2", "WT"])
    w = df["WT"]
    paper = (df[["Q3x1", "Q3x2"]] >= 1).any(axis=1)          # 0=이용안함, 1~5일
    portal = (df[["Q40x1_1", "Q40x1_2", "Q40x2_1", "Q40x2_2"]] >= 1).any(axis=1)
    rows.append({"year": y, "종이신문": r(w, paper), "TV 뉴스": r(w, df["Q11"] == 1),
                 "포털 뉴스": r(w, portal), "동영상 뉴스": r(w, df["Q66"] == 1),
                 "숏폼 뉴스": np.nan, "AI 뉴스": np.nan, "n": len(df)})

# ---- 2022 (n=58,936, WT; 조사설계 상이 — 공식 시계열에서 제외되는 해) ----
df = load(f"{D}/2022_언론수용자조사/2022 언론수용자 조사 DATA_통계표_보고서 등/데이터/2022 언론수용자 조사_개인용_공개용 데이터.SAV",
          ["Q1", "Q19", "Q57", "Q37A_1", "Q37A_2", "Q37B_1", "Q37B_2", "WT"])
w = df["WT"]
portal = (df[["Q37A_1", "Q37A_2", "Q37B_1", "Q37B_2"]] >= 1).any(axis=1)
rows.append({"year": 2022, "종이신문": r(w, df["Q1"] == 1), "TV 뉴스": r(w, df["Q19"] == 1),
             "포털 뉴스": r(w, portal), "동영상 뉴스": r(w, df["Q57"] == 1),
             "숏폼 뉴스": np.nan, "AI 뉴스": np.nan, "n": len(df)})

# ---- 2023 (n=5,000, HMWT) ----
df = load(f"{D}/2023_언론수용자조사/2023 언론수용자 조사 DATA_통계표 등/2. 2023 언론수용자 조사_최종데이터(공개용).sav",
          ["Q1", "Q13", "Q31_1", "Q31_2", "Q52", "Q58", "HMWT"])
w = df["HMWT"]
portal = (df["Q31_1"] == 1) | (df["Q31_2"] == 2)
rows.append({"year": 2023, "종이신문": r(w, df["Q1"] == 1), "TV 뉴스": r(w, df["Q13"] == 1),
             "포털 뉴스": r(w, portal), "동영상 뉴스": r(w, df["Q52"] == 1),
             "숏폼 뉴스": r(w, df["Q58"] == 1), "AI 뉴스": np.nan, "n": len(df)})

# ---- 2024 (n=6,000, WT) ----
df = load(f"{D}/2024_언론수용자조사/3. 2024 언론수용자 조사_최종데이터.sav",
          ["Q1", "Q13", "Q31_1", "Q31_2", "Q52", "Q58", "WT"])
w = df["WT"]
portal = (df["Q31_1"] == 1) | (df["Q31_2"] == 2)
rows.append({"year": 2024, "종이신문": r(w, df["Q1"] == 1), "TV 뉴스": r(w, df["Q13"] == 1),
             "포털 뉴스": r(w, portal), "동영상 뉴스": r(w, df["Q52"] == 1),
             "숏폼 뉴스": r(w, df["Q58"] == 1), "AI 뉴스": np.nan, "n": len(df)})

# ---- 2025 (n=6,000, WT) ----
df = load(f"{D}/2025_언론수용자조사/3. 2025 언론수용자 조사_최종데이터.SAV",
          ["Q1", "Q13", "Q31_1", "Q31_2", "Q53", "Q61", "Q73", "WT"])
w = df["WT"]
portal = (df["Q31_1"] == 1) | (df["Q31_2"] == 2)
rows.append({"year": 2025, "종이신문": r(w, df["Q1"] == 1), "TV 뉴스": r(w, df["Q13"] == 1),
             "포털 뉴스": r(w, portal), "동영상 뉴스": r(w, df["Q53"] == 1),
             "숏폼 뉴스": r(w, df["Q61"] == 1), "AI 뉴스": r(w, df["Q73"] == 1), "n": len(df)})

ts = pd.DataFrame(rows).set_index("year")
ts.to_csv(f"{OUT}/t_timeseries_2018_2025.csv", encoding="utf-8-sig")
print(ts.to_string())

